exports.create = function (ctx) {
  var rand = ctx.random;
  var pool = shuffle(BANK, rand).slice(0, TOTAL_Q);
  var idx = -1;
  var phase = 'intro';        /* intro | question | reveal | done */
  var left = 0;               /* 当前题剩余秒 */
  var scores = {};
  var streak = {};            /* 连对计数 */
  var answered = {};          /* 本题已答的人 → 选项 */
  var locked = {};            /* 答错禁答 */
  var correctCount = 0;
  var over = null;
  var events = [];

  ctx.players.forEach(function (p) { scores[p.id] = 0; streak[p.id] = 0; });

  function cur() { return pool[idx] || null; }
  function nextQuestion() {
    idx += 1;
    if (idx >= pool.length) {
      phase = 'done';
      var rank = Object.keys(scores).map(function (id) {
        var pl = ctx.players.filter(function (p) { return p.id === id; })[0] || { name: '?' };
        return { id: id, name: pl.name, score: scores[id] };
      }).sort(function (a, b) { return b.score - a.score; });
      rank.forEach(function (r, i) { r.rank = i + 1; });
      over = { game: 'quiz', winner: rank[0] ? rank[0].id : null, scores: rank, reason: 'finished' };
      events.push({ e: 'finish' });
      return;
    }
    phase = 'question';
    left = PER_Q;
    answered = {};
    locked = {};
    correctCount = 0;
    events.push({ e: 'q', i: idx });
  }

  nextQuestion();

  var api = {
    _lastQ: -1,
    onAction: function (p, d) {
      if (phase !== 'question' || !d || d.a !== 'answer') return;
      if (answered[p.id] != null || locked[p.id]) return;
      var k = d.k | 0;
      var q = cur();
      if (!q || k < 0 || k >= q.a.length) return;
      answered[p.id] = k;
      if (k === q.k) {
        /* 分数按答对顺序衰减：100 / 80 / 65 / 55 */
        var gain = [100, 80, 65, 55][Math.min(3, correctCount)] || 50;
        correctCount += 1;
        /* 连对加成：每连对一题 +15，最多 +45 */
        var bonus = Math.min(45, (streak[p.id] || 0) * 15);
        streak[p.id] = (streak[p.id] || 0) + 1;
        scores[p.id] = (scores[p.id] || 0) + gain + bonus;
        events.push({ e: 'right', id: p.id, k: k, gain: gain, bonus: bonus, streak: streak[p.id] });
        /* 全员答对或答错，立刻揭晓，不干等满 7 秒 */
        var live = ctx.players.filter(function (x) { return answered[x.id] != null || locked[x.id]; });
        if (live.length >= ctx.players.length) { phase = 'reveal'; left = BETWEEN; events.push({ e: 'reveal', k: q.k }); }
      } else {
        locked[p.id] = true;
        streak[p.id] = 0;
        scores[p.id] = Math.max(0, (scores[p.id] || 0) - 20);
        events.push({ e: 'wrong', id: p.id, k: k });
      }
    },
    step: function (dt) {
      if (phase === 'done') return;
      left -= dt;
      if (left > 0) return;
      if (phase === 'question') {
        phase = 'reveal';
        left = BETWEEN;
        events.push({ e: 'reveal', k: cur() ? cur().k : -1 });
      } else {
        nextQuestion();
      }
    },
    snapshot: function snapshot(tick) {
      var q = cur();
      var out = {
        t: tick, ph: phase, i: idx, n: pool.length,
        left: Math.max(0, Math.round(left * 10) / 10),
        sc: Object.keys(scores).map(function (id) { return [id, scores[id]]; }),
        cb: Object.keys(streak).map(function (id) { return [id, streak[id]]; }),
        ans: Object.keys(answered).map(function (id) { return [id, answered[id]]; })
      };
      if (q) out.cat = q.c;
      /* 题干只在「换题首帧」下发，之后每帧只发状态，省一半带宽 */
      if (q && (phase === 'question' || phase === 'reveal')) {
        if (api._lastQ !== idx) { out.q = { q: q.q, a: q.a }; api._lastQ = idx; }
        if (phase === 'reveal') out.k = q.k;
      }
      if (events.length) { out.ev = events.slice(0, 12); events.length = 0; }
      return out;
    },
    result: function () { return over; }
  };
  return api;
};
